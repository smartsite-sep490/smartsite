import {
  Check,
  Column,
  CreateDateColumn,
  Entity,
  ForeignKey,
  PrimaryColumn,
  Unique,
} from 'typeorm';
import { ZoneEntryAssessmentRequestEntity } from './zone-entry-assessment-request.entity.js';

/**
 * Immutable MF06 authority archive storage.
 * Private projection, not a public DTO or validator. The store/codec validates
 * canonical content; database guards enforce their narrower storage boundary.
 */
@Entity({ name: 'zone_entry_authority_artifact' })
@Unique('mf06_authority_artifact_artifact_id_request_id_key', ['artifactId', 'requestId'])
@ForeignKey(() => ZoneEntryAssessmentRequestEntity, ['requestId'], ['requestId'], {
  name: 'mf06_authority_artifact_request_id_fkey',
  onDelete: 'RESTRICT',
})
@Check('mf06_authority_artifact_sha256_check', "sha256 ~ '^[0-9a-f]{64}$'")
@Check('mf06_authority_artifact_body_hash_check', "body_hash ~ '^[0-9a-f]{64}$'")
@Check('mf06_authority_artifact_body_check', 'octet_length(body::text) <= 2097152')
@Check('mf06_authority_artifact_stored_at_check', 'isfinite(stored_at)')
export class ZoneEntryAuthorityArtifactEntity {
  @PrimaryColumn({
    name: 'artifact_id',
    type: 'uuid',
    primaryKeyConstraintName: 'mf06_authority_artifact_pkey',
    update: false,
  })
  artifactId!: string;

  @Column({ name: 'request_id', type: 'uuid', update: false })
  requestId!: string;

  @Column({ name: 'sha256', type: 'char', length: 64, update: false })
  sha256!: string;

  /** Stored authority payload; excluded from default queries to avoid 2MB buffer overhead. */
  @Column({ name: 'body', type: 'jsonb', select: false, update: false })
  body!: Record<string, unknown>;

  /** Database-computed body text sha256; generated by insert trigger. */
  @Column({ name: 'body_hash', type: 'char', length: 64, insert: false, update: false })
  bodyHash!: string;

  /** Recording timestamp; generated by database clock trigger. */
  @CreateDateColumn({
    name: 'stored_at',
    type: 'timestamptz',
    default: () => 'clock_timestamp()',
    insert: false,
    update: false,
  })
  storedAt!: Date;
}
