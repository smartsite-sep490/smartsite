import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { Injectable, UnauthorizedException } from '@nestjs/common';
import { DataSource, QueryFailedError } from 'typeorm';
import { randomUUID } from 'node:crypto';
import { Transform } from 'class-transformer';
import {
  IsIn,
  IsOptional,
  IsString,
  Matches,
  MaxLength,
  MinLength,
  ValidateIf,
} from 'class-validator';
import {
  command,
  invalid,
  knownUnique,
  missing,
  page,
  uuid,
} from '../../common/configuration/commands.js';
import {
  executeMainMetadataMutation,
  type MainConfigurationCommandContext,
} from '../../common/configuration/main-configuration-authority.js';
import { siteManagerCommandAuthorization } from '../auth/site-manager.guard.js';
import { GateEntity } from '../../database/entities/gate.entity.js';
import { CameraEntity } from '../../database/entities/camera.entity.js';
import { CameraStatus } from '../../database/entities/enums.js';
import { requireActiveGate } from './gate-registry.js';

const trim = ({ value }: { value: unknown }) => (typeof value === 'string' ? value.trim() : value);
export class CreateGateDto {
  @ValidateIf((_object, value) => value !== undefined)
  @Transform(trim)
  @IsString()
  @MinLength(1)
  @MaxLength(64)
  @Matches(/^[A-Za-z0-9][A-Za-z0-9_-]*$/)
  @ApiPropertyOptional({ maxLength: 64, description: 'Generated by the Backend when omitted.' })
  code?: string;
  @Transform(trim)
  @IsString()
  @MinLength(1)
  @MaxLength(100)
  @Matches(/^[^\p{Cc}\p{Cs}]+$/u)
  @ApiProperty({ maxLength: 100 })
  name!: string;
}
export class UpdateGateDto {
  @IsOptional()
  @Transform(trim)
  @IsString()
  @MinLength(1)
  @MaxLength(100)
  @Matches(/^[^\p{Cc}\p{Cs}]+$/u)
  @ApiPropertyOptional({ maxLength: 100 })
  name?: string;
  @IsOptional()
  @IsIn(['ACTIVE', 'INACTIVE'])
  @ApiPropertyOptional({ enum: ['ACTIVE', 'INACTIVE'] })
  status?: 'ACTIVE' | 'INACTIVE';
}

@Injectable()
export class GatesService {
  constructor(private readonly source: DataSource) {}
  async list(siteId: string, offset = 0, limit = 20, status?: string) {
    const scope = uuid(siteId).toLowerCase();
    if (status !== undefined && status !== 'ACTIVE' && status !== 'INACTIVE')
      invalid('Invalid gate status');
    const p = page(offset, limit);
    const [items, total] = await this.source.getRepository(GateEntity).findAndCount({
      where: { siteId: scope, ...(status ? { status: status as 'ACTIVE' | 'INACTIVE' } : {}) },
      order: { code: 'ASC', id: 'ASC' },
      skip: p.offset,
      take: p.limit,
    });
    return { items, total };
  }
  async get(siteId: string, gateId: string) {
    return (
      (await this.source
        .getRepository(GateEntity)
        .findOneBy({ id: uuid(gateId).toLowerCase(), siteId: uuid(siteId).toLowerCase() })) ??
      missing()
    );
  }
  async publicList(siteId: string) {
    const items = await this.source.getRepository(GateEntity).find({
      where: { siteId: uuid(siteId).toLowerCase(), status: 'ACTIVE' },
      order: { code: 'ASC', id: 'ASC' },
      select: { id: true, code: true, name: true },
    });
    return { items: items.map(({ id, code, name }) => ({ id, code, name })) };
  }
  async sources(siteId: string, gateId: string) {
    await requireActiveGate(this.source.manager, siteId, gateId);
    const items = await this.source.getRepository(CameraEntity).find({
      where: {
        siteId: uuid(siteId).toLowerCase(),
        gateId: uuid(gateId).toLowerCase(),
        type: 'GATE',
        status: CameraStatus.ACTIVE,
      },
      select: { id: true, gateId: true, siteId: true, code: true, name: true },
      order: { code: 'ASC', id: 'ASC' },
    });
    return {
      items: items.map(({ id, gateId, siteId, code, name }) => ({
        id,
        gateId: gateId!,
        siteId,
        code,
        name,
      })),
    };
  }
  async create(siteId: string, input: CreateGateDto, context: MainConfigurationCommandContext) {
    const value = command(CreateGateDto, input);
    if (!context?.reauthorize) throw new UnauthorizedException();
    siteId = uuid(siteId).toLowerCase();
    for (let attempt = 0; attempt < 3; attempt++) {
      const id = randomUUID();
      const code = value.code ?? `GATE-${id.replaceAll('-', '').slice(0, 12).toUpperCase()}`;
      try {
        return await executeMainMetadataMutation(
          this.source,
          context,
          (manager) =>
            manager
              .getRepository(GateEntity)
              .save({ id, siteId, code, name: value.name, status: 'ACTIVE' }),
          siteManagerCommandAuthorization(siteId, context.actorUserId),
        );
      } catch (error) {
        if (
          value.code === undefined &&
          attempt < 2 &&
          error instanceof QueryFailedError &&
          error.driverError.code === '23505' &&
          error.driverError.constraint === 'uq_gate_site_code'
        )
          continue;
        knownUnique(error, ['uq_gate_site_code']);
      }
    }
    throw new Error('Gate code allocation did not complete');
  }
  async update(
    siteId: string,
    gateId: string,
    input: UpdateGateDto,
    context: MainConfigurationCommandContext,
  ) {
    const value = command(UpdateGateDto, input);
    if (!context?.reauthorize) throw new UnauthorizedException();
    const updates = Object.fromEntries(
      Object.entries(value).filter(([, field]) => field !== undefined),
    );
    if (!Object.keys(updates).length || value.name === null || value.status === null)
      invalid('Provide a gate name or status');
    siteId = uuid(siteId).toLowerCase();
    gateId = uuid(gateId).toLowerCase();
    return executeMainMetadataMutation(
      this.source,
      context,
      async (manager) => {
        const gate = await manager
          .getRepository(GateEntity)
          .findOne({ where: { id: gateId, siteId }, lock: { mode: 'pessimistic_write' } });
        if (!gate) missing();
        Object.assign(gate, updates);
        return manager.getRepository(GateEntity).save(gate);
      },
      siteManagerCommandAuthorization(siteId, context.actorUserId),
    );
  }
}
